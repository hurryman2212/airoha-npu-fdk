#ifndef AN7581_MEMORY_MAP_H
#define AN7581_MEMORY_MAP_H

#include "an7581/platform/types.h"

#define AN7581_NPU_CORE_COUNT 8U

#define AN7581_NPU_FIRMWARE_BASE UINT32_C(0x84000000)
#define AN7581_NPU_FIRMWARE_MAX_SIZE UINT32_C(0x00200000)
#define AN7581_NPU_RESERVED_SIZE UINT32_C(0x00a00000)

#define AN7581_NPU_MMIO_BASE UINT32_C(0x1e900000)
#define AN7581_NPU_LOCAL_DATA_BASE UINT32_C(0x3e900000)
#define AN7581_NPU_SHARED_SRAM_BASE UINT32_C(0x3e800000)
#define AN7581_NPU_SHARED_SRAM_SIZE UINT32_C(0x00078000)
#define AN7581_NPU_L2_WORKSPACE_BASE UINT32_C(0x3e880000)
#define AN7581_NPU_L2_WORKSPACE_SIZE UINT32_C(0x00040000)
#define AN7581_NPU_L2_CACHE_CONTROL UINT32_C(0x1ec0f200)
#define AN7581_NPU_L2_CACHE_ENABLE UINT32_C(1)
#define AN7581_NPU_MAILBOX_OFFSET UINT32_C(0x0030c000)
#define AN7581_NPU_MAILBOX_BASE                                                \
  (AN7581_NPU_MMIO_BASE + AN7581_NPU_MAILBOX_OFFSET)

#define AN7581_NPU_MIB_BASE (AN7581_NPU_MAILBOX_BASE + UINT32_C(0x140))
#define AN7581_NPU_MIB(index) (AN7581_NPU_MIB_BASE + (index) * sizeof(uint32_t))
#define AN7581_NPU_MIB_0 AN7581_NPU_MIB(0U)
#define AN7581_NPU_MIB_12 AN7581_NPU_MIB(12U)
#define AN7581_NPU_MIB_21 AN7581_NPU_MIB(21U)
#define AN7581_NPU_MIB_31 AN7581_NPU_MIB(31U)

/*
 * These startup registers and their write sequence are present in the recovered
 * EN7581/MT7996 image.  No public register documentation identifies their
 * individual fields, so the names state only the proven boot-time role.
 */
#define AN7581_NPU_COMMON_STARTUP_CONTROL UINT32_C(0x1ec11834)
#define AN7581_NPU_COMMON_STARTUP_TRIGGER UINT32_C(0x1ec00f00)
#define AN7581_NPU_CLOCK_CONFIGURATION UINT32_C(0x1fa201fc)

#define AN7581_PLIC_PRIORITY_BASE UINT32_C(0x0c000004)
#define AN7581_PLIC_ENABLE_SET_BASE UINT32_C(0x0c002000)
#define AN7581_PLIC_ENABLE_CLEAR_BASE UINT32_C(0x0c003000)
#define AN7581_PLIC_CONTEXT_BASE UINT32_C(0x0c200000)

#define AN7581_MBOX_INT_STATUS (AN7581_NPU_MAILBOX_BASE + UINT32_C(0x000))
#define AN7581_MBOX_INT_MASK(core)                                             \
  (AN7581_NPU_MAILBOX_BASE + UINT32_C(0x004) + ((core) * UINT32_C(4)))
#define AN7581_MBQ0_CTRL(core, index)                                          \
  (AN7581_NPU_MAILBOX_BASE + UINT32_C(0x030) + ((core) * UINT32_C(0x10)) +     \
   ((index) * UINT32_C(4)))
#define AN7581_MBQ8_CTRL(core, index)                                          \
  (AN7581_NPU_MAILBOX_BASE + UINT32_C(0x0b0) + ((core) * UINT32_C(0x10)) +     \
   ((index) * UINT32_C(4)))

#define AN7581_LOCAL_TIMER_BASE UINT32_C(0x1ec10100)
#define AN7581_WIFI_RRO_RESULT_TARGET_ADDRESS UINT32_C(0x1fb5080c)
#define AN7581_WIFI_RRO_ALLOCATOR_ACTIVITY_ADDRESS UINT32_C(0x1fb50fe4)
#define AN7581_NPU_UART_BASE UINT32_C(0x1ec10000)
#define AN7581_NPU_UART_DATA_OFFSET UINT32_C(0x00)
#define AN7581_NPU_UART_INTERRUPT_ENABLE_OFFSET UINT32_C(0x04)
#define AN7581_NPU_UART_FIFO_CONTROL_OFFSET UINT32_C(0x08)
#define AN7581_NPU_UART_LINE_CONTROL_OFFSET UINT32_C(0x0c)
#define AN7581_NPU_UART_MODEM_CONTROL_OFFSET UINT32_C(0x10)
#define AN7581_NPU_UART_LINE_STATUS_OFFSET UINT32_C(0x14)
#define AN7581_NPU_UART_HIGH_SPEED_OFFSET UINT32_C(0x24)
#define AN7581_NPU_UART_BAUD_CONFIGURATION_OFFSET UINT32_C(0x2c)

#define AN7581_NPU_WLAN_BASE UINT32_C(0x1ec0d000)
#define AN7581_NPU_WLAN_TX_RING_OFFSET UINT32_C(0x80)
#define AN7581_NPU_WLAN_RING_STRIDE UINT32_C(0x10)
#define AN7581_NPU_WLAN_TX_RING(index)                                         \
  (AN7581_NPU_WLAN_BASE + AN7581_NPU_WLAN_TX_RING_OFFSET +                     \
   (index) * AN7581_NPU_WLAN_RING_STRIDE)
#endif
